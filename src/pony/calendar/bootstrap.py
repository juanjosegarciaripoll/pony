"""First-launch bootstrap: write a config template and offer to edit it.

Triggered from `cli.main()` when a data command runs without a config
file, and used as the body of `pony calendar init`. Both paths share the same
template + editor flow so there is exactly one canonical "first config"
experience.
"""

from __future__ import annotations

import sys
from collections.abc import Callable
from pathlib import Path

from pony.atomic import write_atomically
from pony.calendar.domain import CALENDAR_CONFIG_VERSION

PromptFn = Callable[[str], str]
EditorFn = Callable[[Path], None]
IsInteractiveFn = Callable[[], bool]


# Comments survive only until the first `pony calendar account add ...` (which
# round-trips the parsed config and drops them), so they're written for
# the user's first read, not as a long-lived reference. The canonical
# example reference lives in `config-sample.toml` at the repo root.
_TEMPLATE = b"""\
# calendar configuration
#
# Generated by `pony calendar init`. Path values support ~, $VAR, and %VAR%
# expansion. After editing, run `pony calendar sync` to fetch your calendars,
# or `pony tui` to browse them.

config_version = @CONFIG_VERSION@
use_utf8 = false

# editor = "nvim"   # optional override of $EDITOR / $VISUAL


# ---------------------------------------------------------------------
# Example accounts. Uncomment one and replace placeholders, or use
# `pony calendar account add ...` from the command line instead.
# ---------------------------------------------------------------------

# # Basic auth: Nextcloud, Radicale, Apple Calendar, Baikal, ...
# [[accounts]]
# name = "personal"
# url = "https://caldav.example.com/dav/calendars/user/USER/"
# username = "USER@example.com"
# credential = { backend = "plaintext", password = "REPLACE-ME" }
# # mirror_path is optional; defaults to <calendar root>/mirror/<name>,
# # which is <data_dir>/calendar/mirror/<name> under Pony Express.
# # mirror_path = "~/.local/share/pony/calendar/mirror/personal"
# # trash_retention_days defaults to 30.
# # include / exclude are Python regexes (re.fullmatch); default include = [".*"].

# # Google Calendar via OAuth 2.0. Only the client_id/client_secret from
# # your Google Cloud project are required; the CalDAV URL, username, and
# # OAuth scope are filled in by Pony Express. The OAuth client must be of
# # type "Desktop app" (the same type Thunderbird uses). The first
# # `pony calendar sync` will open your browser to the consent screen and
# # store the tokens automatically.
# [[accounts]]
# name = "google"
# [accounts.credential]
# backend = "google"
# client_id = "REPLACE-ME.apps.googleusercontent.com"
# client_secret = "REPLACE-ME"

# # Generic OAuth 2.0 (Microsoft / Outlook, custom IdPs): configure URL,
# # username, scope, and client credentials explicitly. The first sync
# # opens a browser using the loopback redirect flow (RFC 8252 + PKCE).
# [[accounts]]
# name = "outlook"
# url = "https://outlook.office365.com/"
# username = "you@outlook.com"
# [accounts.credential]
# backend = "oauth"
# client_id = "REPLACE-ME"
# client_secret = "REPLACE-ME"
# scope = "https://outlook.office.com/Calendars.ReadWrite"
"""

# The schema number is substituted rather than written out, so a bump
# to `CALENDAR_CONFIG_VERSION` cannot leave the template behind writing
# a file its own loader would then refuse.
TEMPLATE_TOML = _TEMPLATE.replace(
    b"@CONFIG_VERSION@", str(CALENDAR_CONFIG_VERSION).encode("ascii")
)


def write_template(config_path: Path) -> None:
    """Write `TEMPLATE_TOML` to `config_path` atomically (temp + rename)."""
    write_atomically(config_path, TEMPLATE_TOML, suffix=".toml")


def default_is_interactive() -> bool:
    """Both stdin and stdout must be a TTY for the prompt to be useful."""
    return sys.stdin.isatty() and sys.stdout.isatty()


def default_prompt(message: str) -> str:
    return input(message)


__all__ = [
    "TEMPLATE_TOML",
    "EditorFn",
    "IsInteractiveFn",
    "PromptFn",
    "default_is_interactive",
    "default_prompt",
    "write_template",
]
